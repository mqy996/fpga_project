`timescale 1ns / 1ps
`default_nettype none

// Transfers one software START or STOP transaction from the 125 MHz control
// plane to the 32 MHz acquisition controller.  The command response is
// released when the 32 MHz domain has *accepted* the command (the return
// leg of u_operation_cdc), rather than waiting for a one-cycle state-machine
// completion indication.  A START/STOP action must never be allowed to take
// effect while its UDP control response is lost.  State validity is checked
// in runtime_config_manager from the synchronised run-state flags before the
// command is sent.
//
// u_operation_cdc uses DEST_EXT_HSK, so the destination acknowledgement is
// held until the asynchronous source withdraws its request.  This makes the
// delivery acknowledgement a stable, lossless 32 MHz -> 125 MHz event.
module run_control_cdc_bridge(
    input  wire       src_clk,
    input  wire       src_rst,
    input  wire       src_start,
    input  wire       src_stop,
    output wire       src_busy,
    output reg        src_done,
    output reg [3:0]  src_status,

    input  wire       dst_clk,
    input  wire       dst_rst,
    output reg        dst_start_pulse,
    output reg        dst_stop_pulse,
    input  wire       dst_done,
    input  wire [3:0] dst_status
);
    localparam [1:0] OP_START = 2'd1, OP_STOP = 2'd2;

    reg [1:0] op_payload;
    reg op_send;
    // Source-domain ownership state.  Do not use op_request in this domain:
    // it is produced by the 32 MHz XPM destination and would be a raw reverse
    // CDC path if used in the 125 MHz control manager.
    reg src_operation_inflight;
    // Small source-clock release guard after an XPM acknowledgement.  Apart
    // from observing src_rcv low, this gives the four-phase macro time to
    // complete its internally synchronised return transition before another
    // source request may rise.
    reg [2:0] src_release_count;
    wire op_received;
    wire [1:0] op_dst;
    wire op_request;
    reg op_ack;
    reg op_seen;
    // XPM requires src_rcv to return low before the next src_send rising
    // edge.  Keep busy through that release phase as well.
    assign src_busy = op_send || src_operation_inflight || op_received ||
                      (src_release_count != 0);

    // 125 MHz source: hold the requested operation until the 32 MHz domain
    // has accepted it.  op_received is the synchronised return handshake of
    // u_operation_cdc, not a one-cycle pulse generated by the run FSM.
    always @(posedge src_clk) begin
        if (src_rst) begin
            op_payload <= 0;
            op_send <= 0;
            src_operation_inflight <= 0;
            src_release_count <= 0;
            src_done <= 0;
            src_status <= 0;
        end else begin
            src_done <= 0;
            if (src_release_count != 0)
                src_release_count <= src_release_count - 1'b1;
            if (op_send && op_received) begin
                op_send <= 0;
                src_operation_inflight <= 0;
                src_release_count <= 3'd4;
                src_done <= 1'b1;
                src_status <= 4'd0;
            end
            if (!op_send && !src_operation_inflight && !op_received &&
                (src_release_count == 0) && (src_stop || src_start)) begin
                // STOP has priority if a caller accidentally asserts both.
                op_payload <= src_stop ? OP_STOP : OP_START;
                op_send <= 1;
                src_operation_inflight <= 1;
            end

        end
    end

    // 32 MHz destination: one request produces exactly one pulse to the
    // run controller.  dst_done/dst_status remain interface-visible for
    // diagnostics and compatibility with the run controller, but are not
    // used as a CDC completion source: they are only one dst_clk cycle long.
    always @(posedge dst_clk) begin
        if (dst_rst) begin
            op_ack <= 0;
            op_seen <= 0;
            dst_start_pulse <= 0;
            dst_stop_pulse <= 0;
        end else begin
            dst_start_pulse <= 0;
            dst_stop_pulse <= 0;

            if (!op_request) begin
                op_ack <= 0;
                op_seen <= 0;
            end else if (!op_seen) begin
                op_ack <= 1;
                op_seen <= 1;
                if (op_dst == OP_STOP)
                    dst_stop_pulse <= 1;
                else
                    dst_start_pulse <= 1;
            end

        end
    end

    xpm_cdc_handshake #(
        .DEST_EXT_HSK(1), .DEST_SYNC_FF(2), .INIT_SYNC_FF(1),
        .SIM_ASSERT_CHK(1), .SRC_SYNC_FF(2), .WIDTH(2)
    ) u_operation_cdc (
        .src_clk(src_clk), .src_in(op_payload), .src_send(op_send), .src_rcv(op_received),
        .dest_clk(dst_clk), .dest_out(op_dst), .dest_req(op_request), .dest_ack(op_ack)
    );
endmodule

`default_nettype wire
